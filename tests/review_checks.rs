    let report = scan(root, &[ModuleId::Persistence]);
    let mut levels: Vec<Severity> = of(&report, "PERS-VSCODE-TASK").iter().map(|f| f.severity).collect();
    levels.sort();
    assert_eq!(levels, vec![Severity::Medium, Severity::High]);
