fn write(root: &Path, abs: &str, content: &str) {
    let p = root.join(abs.trim_start_matches('/'));
    fs::create_dir_all(p.parent().expect("parent")).expect("mkdir");
    fs::write(p, content).expect("write");
}

fn scan(root: &Path, modules: &[ModuleId]) -> Report {
    let opts = ScanOptions { modules: modules.to_vec(), ..ScanOptions::default() };
    run_scan(&SysRoot::new(root), &Config::default(), &opts, &|_| {})
}

fn of<'a>(report: &'a Report, rule: &str) -> Vec<&'a Finding> {
    report.findings.iter().filter(|f| f.rule == rule).collect()
}

#[test]
fn address_rules_with_ports_sets_and_jumps_are_found() {
    let nft = "table inet filter { # handle 1
 set friends {
  type ipv4_addr
  elements = { 192.168.1.9,
               198.51.100.4 }
 }
 chain in {
  type filter hook input priority filter; policy drop;
  ct state established,related accept
  jump doors
 }
 chain doors {
  ip saddr 203.0.113.7 tcp dport 22 counter packets 9 bytes 800 accept
  ip saddr @friends accept
  ip saddr 203.0.113.8 ct state established,related accept
  ip saddr != 10.0.0.0/8 drop
 }
 chain forward {
  type filter hook forward priority filter;
  ip saddr 203.0.113.9 accept
 }
}
";
    let rules = read_ruleset(nft);
    assert!(rules.protects);
    assert_eq!(
        rules.public_allows,
        vec!["chain doors: ip saddr 203.0.113.7 tcp dport 22 accept", "chain doors: ip saddr @friends accept [@friends = 192.168.1.9, 198.51.100.4]"]
    );
    assert!(rules.accepts.contains("incoming inet filter doors: ip saddr 203.0.113.7 tcp dport 22 accept"));
    assert!(rules.accepts.contains("other inet filter forward: ip saddr 203.0.113.9 accept"));
    // counters do not make a rule look new
    assert_eq!(read_ruleset(&nft.replace("packets 9 bytes 800", "packets 12 bytes 9000")).accepts, rules.accepts);
}

#[test]
fn the_old_iptables_firewall_counts() {
    let saved = "# Generated by iptables-save
*nat
:PREROUTING ACCEPT [0:0]
-A PREROUTING -s 203.0.113.1/32 -j ACCEPT
COMMIT
*filter
:INPUT DROP [12:900]
:FORWARD ACCEPT [0:0]
:OUTPUT ACCEPT [0:0]
:mine - [0:0]
-A INPUT -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT
-A INPUT -j mine
-A mine -s 203.0.113.5/32 -p tcp -m tcp --dport 22 -j ACCEPT
-A mine ! -s 203.0.113.6/32 -j DROP
-A mine -s 192.168.1.0/24 -j ACCEPT
COMMIT
";
    let rules = read_iptables(saved, "ip");
    assert!(rules.protects);
    assert_eq!(rules.public_allows, vec!["chain mine: -s 203.0.113.5/32 -p tcp -m tcp --dport 22 -j ACCEPT  (iptables-legacy)"]);
    assert_eq!(rules.accepts.iter().filter(|r| r.starts_with("incoming ")).count(), 3);
    assert!(read_iptables("*filter\n:INPUT ACCEPT [0:0]\n-A INPUT -j REJECT --reject-with icmp-port-unreachable\nCOMMIT\n", "ip").protects);
    assert!(!read_iptables("*filter\n:INPUT ACCEPT [0:0]\n-A INPUT -s 203.0.113.5/32 -j DROP\nCOMMIT\n", "ip").protects);
}

#[test]
fn a_new_accept_rule_is_a_change() {
    let dir = tempfile::tempdir().expect("tempdir");
    let mut report = scan(dir.path(), &[ModuleId::NetProc]);
    report.inventory.firewall_rules = Some(vec!["incoming ip filter INPUT: tcp dport 22 accept".into()]);
    let base = Baseline::from_report(&report);
    let mut now = report.inventory.clone();
    now.firewall_rules = Some(vec![
        "incoming ip filter INPUT: tcp dport 22 accept".into(),
        "incoming ip filter INPUT: ip saddr 203.0.113.7 tcp dport 22 accept".into(),
        "other ip filter DOCKER: tcp dport 80 accept".into(),
    ]);
    let (changes, _) = baseline::compare(&base, &now, &report.modules);
    let mut levels: Vec<Severity> = changes.iter().filter(|f| f.rule == "BASE-FIREWALL-RULE").map(|f| f.severity).collect();
    levels.sort();
    assert_eq!(levels, vec![Severity::Low, Severity::Medium]);
    // not read this time: nothing to compare
    now.firewall_rules = None;
    assert!(baseline::compare(&base, &now, &report.modules).0.iter().all(|f| f.rule != "BASE-FIREWALL-RULE"));
}

