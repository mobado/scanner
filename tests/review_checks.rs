#[test]
fn a_search_that_stops_early_says_so() {
    take_cut_short();
    assert_eq!(capped(0..3, 3, "three things").count(), 3);
    assert!(take_cut_short().is_empty());
    assert_eq!(capped(0..4, 3, "four things").count(), 3);
    let notes = take_cut_short();
    assert!(notes.len() == 1 && notes[0].contains("four things") && notes[0].contains('3'), "{notes:?}");

    // the note reaches the report
    let dir = tempfile::tempdir().expect("tempdir");
    let root = dir.path();
    for n in 0..501 {
        write(root, &format!("/etc/polkit-1/rules.d/{n}.rules"), "// nothing\n");
    }
    let report = scan(root, &[ModuleId::Persistence]);
    assert!(report.notes.iter().any(|n| n.contains("Incomplete") && n.contains("/etc/polkit-1")), "{:?}", report.notes);
}
